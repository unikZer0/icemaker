const { test } = require('node:test');
const assert = require('node:assert/strict');
const { once } = require('node:events');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const mqtt = require('mqtt');
const { start } = require('../server');
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
test('MQTT authentication, live telemetry, isolation, persistence and local API protection', async t => {
  const dataDir = await fs.mkdtemp(path.join(os.tmpdir(), 'icemaker-test-'));
  let app = start({ dataDir, httpPort: 0, mqttPort: 0, mqttHost: '127.0.0.1', quiet: true });
  let client;
  t.after(async () => { if (client) await client.endAsync(true); await app.close(); assert.ok(path.resolve(dataDir).startsWith(path.resolve(os.tmpdir()) + path.sep + 'icemaker-test-')); await fs.rm(dataDir, { recursive: true, force: true }); });
  await Promise.all([once(app.server, 'listening'), once(app.mqttServer, 'listening')]);
  let base = `http://127.0.0.1:${app.server.address().port}`;
  const setup = await (await fetch(base + '/api/setup')).json();
  const brokerUrl = `mqtt://127.0.0.1:${setup.mqttPort}`;
  const wrong = mqtt.connect(brokerUrl, { username: 'incorrect', reconnectPeriod: 0 });
  const [error] = await once(wrong, 'error'); assert.match(error.message, /Not authorized/); await wrong.endAsync(true);
  client = await mqtt.connectAsync(brokerUrl, { username: setup.token, reconnectPeriod: 0 });
  await client.publishAsync('v1/devices/me/attributes', JSON.stringify({ deviceName: 'test-unit', temperatureSensorStatus: false, token: 'must-not-store' }), { qos: 1 });
  await client.publishAsync('v1/devices/me/telemetry', JSON.stringify({ acLineVoltage: 23.5, compressorCurrent: 4.24, waterTemperature: 0 }), { qos: 1 });
  let state;
  for (let i = 0; i < 100; i++) { state = await (await fetch(base + '/api/state')).json(); if (state.latest.wifi.acLineVoltage) break; await delay(20); }
  assert.equal(state.wifi.connected, true);
  assert.equal(state.latest.wifi.acLineVoltage.value, 23.5);
  assert.equal(state.latest.wifi.temperatureSensorStatus.value, false);
  assert.equal(state.latest.wifi.token, undefined);
  assert.deepEqual(state.latest.usb, {});
  const history = await (await fetch(base + '/api/history?source=wifi&hours=1')).json();
  assert.equal(history.length, 2);
  assert.equal((await fetch(base + '/api/history?source=wifi&hours=999')).status, 400);
  assert.equal((await fetch(base + '/api/usb/disconnect', { method: 'POST', headers: { Origin: 'http://evil.example', 'Content-Type': 'application/json' }, body: '{}' })).status, 403);
  assert.equal((await fetch(base + '/api/usb/connect', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ path: 'NOT-A-PORT', baudRate: 115200 }) })).status, 400);
  assert.equal((await fetch(base + '/data/config.json')).status, 404);
  assert.equal((await fetch(base + '/')).status, 200);
  assert.equal((await fetch(base + '/app.js')).status, 200);
  await client.endAsync(); client = undefined;
  await app.close();
  app = start({ dataDir, httpPort: 0, mqttPort: 0, mqttHost: '127.0.0.1', quiet: true });
  await Promise.all([once(app.server, 'listening'), once(app.mqttServer, 'listening')]);
  base = `http://127.0.0.1:${app.server.address().port}`;
  state = await (await fetch(base + '/api/state')).json();
  assert.equal(state.wifi.connected, false); assert.deepEqual(state.latest.wifi, {});
  assert.equal((await (await fetch(base + '/api/history?source=wifi&hours=1')).json()).length, 2);
  assert.equal((await (await fetch(base + '/api/setup')).json()).token, setup.token);
});
